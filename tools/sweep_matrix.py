"""Write docs/workflow-matrix.md: every ComfyQ workflow, what the sweep found (live_check/sweep/*.json),
and the VRAM / time ComfyQ has measured (its calibration). Untested workflows are listed too.

  .venv\\Scripts\\python tools\\sweep_matrix.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "extension" / "comfyq_bridge"))

from client.api import ComfyQClient
from client.profile import load_profile

SWEEP = ROOT / "live_check" / "sweep"
OUT = ROOT / "docs" / "workflow-matrix.md"
GROUPS = {"t2i": "Image", "image-edit": "Image", "i2i": "Image", "i2v": "Video", "video-edit": "Video",
          "3d": "3D", "audio": "Audio"}


def group(w) -> str:
    if w.category == "3d" and ("splat" in w.id or "gaussian" in " ".join(w.tags)):
        return "Splats"
    return GROUPS.get(w.category, "Tools")


def cell(rec: dict | None) -> tuple[str, str, str, str]:
    """(result, run time, import, notes)"""
    if rec is None:
        return "not tested yet", "", "", "serve it, then run the sweep"
    res = rec.get("result", "?")
    if res == "ok" and rec.get("review"):
        res = "ok (to review)"
    mark = {"ok": "✅ ok", "ok (to review)": "⚠️ runs, see notes", "ok (import issue)": "⚠️ ok, import issue",
            "skipped": "⏭ not run (could not be served)", "black output": "❌ black output"}.get(res, f"❌ {res}")
    secs = f"{rec['seconds']} s" if rec.get("seconds") else ""
    imp = "; ".join(rec.get("imported") or [])
    notes = [rec.get("error") or "", rec.get("review") or ""]       # review = what a person saw in the result
    cal = rec.get("calibration") or {}
    if cal and not cal.get("ok"):
        notes.append(f"calibration: {cal.get('error')}")
    notes += [n for n in rec.get("notes", []) if n.startswith("cheap settings")]
    return mark, secs, imp.replace("|", "/"), " · ".join(n for n in notes if n).replace("|", "/")


def main() -> None:
    client = ComfyQClient(load_profile())
    wfs = client.workflows(include_unavailable=True)
    served = client.served_ids() if hasattr(client, "served_ids") else set()
    recs = {}
    for f in sorted(SWEEP.glob("*.json")):
        try:
            d = json.loads(f.read_text(encoding="utf-8"))
            recs[d["id"]] = d
        except (ValueError, KeyError):
            continue
    tested = sum(1 for w in wfs if w.id in recs and recs[w.id].get("result") != "skipped")
    ok = sum(1 for w in wfs if recs.get(w.id, {}).get("result", "").startswith("ok"))
    lines = [
        "# ComfyQ workflow matrix (P1.5)", "",
        ("Every workflow of the classroom ComfyQ, run from Blender through the bridge (`tools\\smoke_test.ps1 "
        "-Sweep`: whatever is **served** is calibrated by ComfyQ, then booked with scene inputs — clay still / "
        "first 2 s of the clay animation / mask / a test sound — and its cheapest settings; the result is "
        "downloaded and imported). VRAM and time come from ComfyQ's own calibration."), "",
        f"**{tested} / {len(wfs)} tested, {ok} ok.** Generated by `tools/sweep_matrix.py`.", "",
        "| Group | Workflow | Inputs | Result | VRAM peak | Calibrated time | Run from Blender | Import | Notes |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for w in sorted(wfs, key=lambda w: (group(w), w.id)):
        rec = recs.get(w.id)
        res, secs, imp, notes = cell(rec)
        vram = f"{w.vram_peak_gb:.1f} GB" if w.vram_peak_gb else "?"
        est = f"{w.estimated_sec:.0f} s" if w.estimated_sec else ""
        inputs = ", ".join((rec or {}).get("inputs", [])) or ""
        name = f"{w.name}<br>`{w.id}`" + (" ▶" if w.id in served else "") + (" (unavailable)" if w.unavailable else "")
        lines.append(f"| {group(w)} | {name} | {inputs} | {res} | {vram} | {est} | {secs} | {imp} | {notes} |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({tested}/{len(wfs)} tested, {ok} ok)")


if __name__ == "__main__":
    main()
